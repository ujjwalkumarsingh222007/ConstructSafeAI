"""ConstructSafe AI - Static Image Hazard Detector Engine
Implements YOLO-based static image hazard analysis for construction site photographs.
Strictly follows model truthfulness: differentiates custom hazard models, standard COCO
weights, and clearly-labelled demo/testing modes.
"""

import io
import os
import logging
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, List, Any, Optional, Union

# Prevent ultralytics from attempting background pip install on unidentifiable image bytes
os.environ["YOLO_AUTO_INSTALL"] = "0"
try:
    import ultralytics.utils.patches as _patches
    _patches._pil_plugins_registered = True
except Exception:
    pass

from PIL import Image, UnidentifiedImageError

logger = logging.getLogger("constructsafe.ai_engine.detector")

# Allowed photo formats for construction hazard evidence
ALLOWED_FORMATS = {"JPEG", "JPG", "PNG", "WEBP"}
MAX_IMAGE_SIZE_BYTES = 10 * 1024 * 1024  # 10 MB

class HazardDetector:
    """YOLOv8-based Construction Site Hazard Detector for static photographs."""

    def __init__(
        self,
        model_path: Optional[str] = None,
        device: Optional[str] = None,
        force_demo_mode: Optional[bool] = None,
        confidence_threshold: float = 0.25,
    ):
        """
        Initialize the hazard detector.
        
        Args:
            model_path: Path to custom hazard weights (.pt). Defaults to env HAZARD_MODEL_PATH
                        or 'ai_engine/models/hazard_yolov8.pt'.
            device: 'cuda', 'cpu', or None (auto-detect via torch.cuda.is_available()).
            force_demo_mode: If True, forces demo/testing mode even if weights are present.
            confidence_threshold: Minimum confidence score to include detection (0.0 to 1.0).
        """
        import torch
        
        # 1. Device selection
        if device is not None:
            self.device = device
        else:
            self.device = "cuda" if torch.cuda.is_available() else "cpu"
        
        self.confidence_threshold = confidence_threshold
        self.model_version = "v1.0"
        
        # 2. Determine model path
        default_custom_path = os.environ.get(
            "HAZARD_MODEL_PATH",
            str(Path(__file__).resolve().parent / "models" / "hazard_yolov8.pt")
        )
        self.model_path = model_path or default_custom_path
        
        # 3. Model truthfulness & mode determination
        # Check if custom hazard weights exist
        self.is_custom_hazard_model = False
        self.is_simulated = False
        self.model = None
        self.mode = "standard_coco"  # 'custom_hazard', 'standard_coco', 'demo_testing'
        
        env_demo = os.environ.get("HAZARD_DEMO_MODE", "false").lower() in ("true", "1", "yes")
        if force_demo_mode or env_demo:
            self._init_demo_mode()
        elif os.path.exists(self.model_path):
            self._init_custom_model()
        else:
            # Fallback check: base yolov8n.pt
            base_model_path = Path(__file__).resolve().parent / "models" / "yolov8n.pt"
            if base_model_path.exists():
                self._init_coco_fallback(str(base_model_path))
            else:
                logger.warning("No custom weights or base weights found. Entering demo/testing mode.")
                self._init_demo_mode()

    def _init_custom_model(self):
        """Loads verified custom construction hazard model weights."""
        from ultralytics import YOLO
        try:
            logger.info(f"Loading custom hazard weights from: {self.model_path} onto {self.device}")
            self.model = YOLO(self.model_path)
            self.model.to(self.device)
            self.is_custom_hazard_model = True
            self.is_simulated = False
            self.mode = "custom_hazard"
            self.model_name = "ConstructSafe YOLOv8 Hazard Detector (Custom Weights)"
            self.disclaimer = (
                "AI detections are generated by custom construction hazard model weights. "
                "Findings are advisory suggestions only and must be confirmed by a licensed Safety Inspector."
            )
        except Exception as e:
            logger.error(f"Failed to load custom model from {self.model_path}: {e}. Falling back to demo mode.")
            self._init_demo_mode()

    def _init_coco_fallback(self, base_path: str):
        """Loads base COCO weights and documents explicit limitation."""
        from ultralytics import YOLO
        try:
            logger.info(f"Loading standard COCO weights from {base_path} onto {self.device}")
            self.model = YOLO(base_path)
            self.model.to(self.device)
            self.is_custom_hazard_model = False
            self.is_simulated = False
            self.mode = "standard_coco"
            self.model_name = "YOLOv8 Standard COCO Detector (Base Model)"
            self.disclaimer = (
                "STANDARD COCO MODEL: Pretrained on general COCO dataset (80 general object classes). "
                "This model detects general objects (e.g. person) but does NOT classify specialized construction "
                "hazards (hard hats, safety vests, harnesses, spill hazards). "
                "Inspector verification is strictly mandatory."
            )
        except Exception as e:
            logger.error(f"Failed to load base weights from {base_path}: {e}. Falling back to demo mode.")
            self._init_demo_mode()

    def _init_demo_mode(self):
        """Configures clearly-labelled demo / simulated testing mode."""
        self.is_custom_hazard_model = False
        self.is_simulated = True
        self.mode = "demo_testing"
        self.model_name = "ConstructSafe YOLOv8 Hazard Detector (Demo/Testing Mode)"
        self.disclaimer = (
            "DEMO / TESTING MODE: Custom construction hazard weights not installed on this server. "
            "Detections are simulated for workflow demonstration and testing only. "
            "Never use simulated detections for automatic compliance or safety sign-off."
        )
        logger.info("Hazard detector initialized in DEMO/TESTING mode (simulated detections).")

    @staticmethod
    def validate_image_bytes(image_bytes: bytes) -> Image.Image:
        """
        Validate image data size, format, and Pillow integrity.
        Raises ValueError if image is invalid, corrupted, or exceeds size limit.
        """
        if not image_bytes:
            raise ValueError("Empty image data provided.")
        
        if len(image_bytes) > MAX_IMAGE_SIZE_BYTES:
            raise ValueError(f"Image exceeds maximum allowable size of {MAX_IMAGE_SIZE_BYTES // (1024*1024)}MB.")
        
        try:
            # First pass: Pillow verify
            temp_stream = io.BytesIO(image_bytes)
            with Image.open(temp_stream) as img:
                img_format = img.format
                if not img_format or img_format.upper() not in ALLOWED_FORMATS:
                    raise ValueError(
                        f"Unsupported image format: {img_format}. Allowed formats: {', '.join(sorted(ALLOWED_FORMATS))}."
                    )
                img.verify()
            
            # Second pass: reopen for reading dimensions and converting to RGB
            img = Image.open(io.BytesIO(image_bytes))
            if img.mode != "RGB":
                img = img.convert("RGB")
            return img
        except (UnidentifiedImageError, OSError) as e:
            raise ValueError(f"Corrupted or unreadable image file: {str(e)}") from e

    def analyze_image(
        self,
        image_input: Union[bytes, str, Path, Image.Image],
        simulate_hazard_categories: Optional[List[str]] = None
    ) -> Dict[str, Any]:
        """
        Analyze a static construction photograph for safety hazards.
        
        Args:
            image_input: Raw image bytes, file path, Path object, or PIL Image.
            simulate_hazard_categories: Optional list of categories for demo/testing mode.
            
        Returns:
            Dict containing model metadata, analysis timestamp, bounding boxes,
            confidence scores, suggested categories, and explicit disclaimer.
        """
        # Load and validate PIL Image
        if isinstance(image_input, (bytes, bytearray)):
            img = self.validate_image_bytes(image_input)
        elif isinstance(image_input, (str, Path)):
            with open(image_input, "rb") as f:
                img = self.validate_image_bytes(f.read())
        elif isinstance(image_input, Image.Image):
            img = image_input.convert("RGB") if image_input.mode != "RGB" else image_input
        else:
            raise ValueError(f"Unsupported image_input type: {type(image_input)}")

        width, height = img.size
        analyzed_at = datetime.now(timezone.utc).isoformat()
        
        # Route inference based on mode
        if self.is_simulated or self.mode == "demo_testing":
            detections = self._generate_demo_detections(width, height, simulate_hazard_categories)
        else:
            detections = self._run_yolo_inference(img, width, height)
            
        # Extract unique suggested categories
        suggested_categories = list(dict.fromkeys(d["category"] for d in detections))
        
        return {
            "model_name": self.model_name,
            "model_version": self.model_version,
            "is_custom_hazard_model": self.is_custom_hazard_model,
            "is_simulated": self.is_simulated,
            "mode": self.mode,
            "device": self.device,
            "analyzed_at": analyzed_at,
            "image_width": width,
            "image_height": height,
            "detections": detections,
            "suggested_categories": suggested_categories,
            "disclaimer": self.disclaimer
        }

    def _run_yolo_inference(self, img: Image.Image, width: int, height: int) -> List[Dict[str, Any]]:
        """Run actual YOLO inference using PyTorch/Ultralytics."""
        detections: List[Dict[str, Any]] = []
        try:
            results = self.model.predict(
                source=img,
                conf=self.confidence_threshold,
                device=self.device,
                verbose=False
            )
            
            for r in results:
                boxes = r.boxes
                if boxes is None:
                    continue
                for box in boxes:
                    conf = float(box.conf[0].item())
                    cls_id = int(box.cls[0].item())
                    cls_name = self.model.names.get(cls_id, f"class_{cls_id}")
                    
                    # xyxy coordinates in absolute pixels
                    xyxy = box.xyxy[0].tolist()
                    x1, y1, x2, y2 = [round(float(v), 2) for v in xyxy]
                    
                    # Normalized coordinates [ymin, xmin, ymax, xmax] (0.0 to 1.0)
                    ymin = max(0.0, min(1.0, round(y1 / height, 4)))
                    xmin = max(0.0, min(1.0, round(x1 / width, 4)))
                    ymax = max(0.0, min(1.0, round(y2 / height, 4)))
                    xmax = max(0.0, min(1.0, round(x2 / width, 4)))
                    
                    detections.append({
                        "category": cls_name,
                        "confidence": round(conf, 4),
                        "bbox": [x1, y1, x2, y2],
                        "normalized_bbox": [ymin, xmin, ymax, xmax]
                    })
        except Exception as e:
            logger.error(f"Error during YOLO inference: {e}", exc_info=True)
            # In case of inference runtime exception, raise or return empty with logged error
            raise RuntimeError(f"YOLO inference failed: {str(e)}") from e
            
        return detections

    def _generate_demo_detections(
        self,
        width: int,
        height: int,
        categories: Optional[List[str]] = None
    ) -> List[Dict[str, Any]]:
        """Generate clearly-labelled simulated detections for testing/demo workflows."""
        cats = categories or ["no_hard_hat", "no_safety_vest", "trip_hazard"]
        detections = []
        
        # Generate predictable bounding boxes within image bounds for testing
        box_configs = [
            # [ymin, xmin, ymax, xmax], category, confidence
            ([0.15, 0.35, 0.40, 0.65], cats[0] if len(cats) > 0 else "no_hard_hat", 0.92),
            ([0.38, 0.30, 0.75, 0.70], cats[1] if len(cats) > 1 else "no_safety_vest", 0.88),
            ([0.72, 0.20, 0.92, 0.60], cats[2] if len(cats) > 2 else "trip_hazard", 0.76),
        ]
        
        for norm_box, cat, conf in box_configs:
            ymin, xmin, ymax, xmax = norm_box
            x1 = round(xmin * width, 2)
            y1 = round(ymin * height, 2)
            x2 = round(xmax * width, 2)
            y2 = round(ymax * height, 2)
            
            detections.append({
                "category": cat,
                "confidence": conf,
                "bbox": [x1, y1, x2, y2],
                "normalized_bbox": [ymin, xmin, ymax, xmax]
            })
            
        return detections
